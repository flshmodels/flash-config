"""Check item catalogs and generate a Roblox ModuleScript. Python 3.11+."""
import argparse
import csv
import io
import json
import os
from pathlib import Path
import re
import sys
import tempfile

MAX_BYTES = 1_048_576
MAX_ITEMS = 10_000
MAX_PRICE = 9_007_199_254_740_991
ID = re.compile(r"[A-Za-z][A-Za-z0-9_-]{0,63}\Z")
FIELDS = {"id", "name", "price", "requires"}


class CatalogError(ValueError):
    pass


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise CatalogError(f"duplicate JSON field: {key}")
        result[key] = value
    return result


def reject_nonfinite_number(value):
    raise CatalogError(f"invalid number: {value}")


def load_catalog(path):
    path = Path(path)
    with path.open("rb") as stream:
        raw = stream.read(MAX_BYTES + 1)
    if len(raw) > MAX_BYTES:
        raise CatalogError("input exceeds 1 MiB")
    text = raw.decode("utf-8-sig")
    if path.suffix.lower() == ".json":
        rows = json.loads(
            text,
            object_pairs_hook=unique_object,
            parse_constant=reject_nonfinite_number,
        )
    elif path.suffix.lower() == ".csv":
        reader = csv.DictReader(io.StringIO(text, newline=""), strict=True)
        headers = reader.fieldnames
        if not headers or len(set(headers)) != len(headers) or set(headers) - FIELDS or not {"id", "name", "price"} <= set(headers):
            raise CatalogError("CSV headers must be id,name,price and optional requires")
        rows = []
        for line, row in enumerate(reader, 2):
            if None in row or any(value is None for value in row.values()):
                raise CatalogError(f"CSV record {line}: wrong number of columns")
            price = row["price"]
            if not re.fullmatch(r"0|[1-9][0-9]{0,15}", price):
                raise CatalogError(f"CSV record {line}: price must be a nonnegative integer")
            row["price"] = int(price)
            if row.get("requires") == "":
                row.pop("requires")
            rows.append(row)
    else:
        raise CatalogError("input must be .json or .csv")
    return validate(rows)


def validate(rows):
    if not isinstance(rows, list) or not 1 <= len(rows) <= MAX_ITEMS:
        raise CatalogError(f"catalog must be an array of 1..{MAX_ITEMS} items")
    result, by_id = [], {}
    for index, row in enumerate(rows, 1):
        prefix = f"item {index}"
        if not isinstance(row, dict) or set(row) - FIELDS or not {"id", "name", "price"} <= set(row):
            raise CatalogError(f"{prefix}: expected id, name, price and optional requires")
        item_id, name, price = row["id"], row["name"], row["price"]
        if not isinstance(item_id, str) or not ID.fullmatch(item_id):
            raise CatalogError(f"{prefix}: invalid id (use a letter, then letters, digits, _ or -, max 64)")
        if item_id in by_id:
            raise CatalogError(f"{prefix}: duplicate id {item_id}")
        if not isinstance(name, str) or not name.strip() or len(name) > 120:
            raise CatalogError(f"{prefix}: name must contain 1..120 characters")
        # Reject isolated JSON surrogates rather than generating unusable UTF-8.
        name.encode("utf-8")
        if type(price) is not int or not 0 <= price <= MAX_PRICE:
            raise CatalogError(f"{prefix}: price must be an integer in 0..{MAX_PRICE}")
        item = {"id": item_id, "name": name, "price": price}
        if "requires" in row:
            required = row["requires"]
            if not isinstance(required, str) or not ID.fullmatch(required):
                raise CatalogError(f"{prefix}: requires must be a valid item id")
            item["requires"] = required
        result.append(item)
        by_id[item_id] = item
    for item in result:
        if "requires" in item and item["requires"] not in by_id:
            raise CatalogError(f"{item['id']}: unknown prerequisite {item['requires']}")
    # Iterative traversal also handles long chains without Python recursion limits.
    done = set()
    for item in result:
        trail, current = set(), item["id"]
        while current is not None and current not in done:
            if current in trail:
                raise CatalogError(f"prerequisite cycle involving {current}")
            trail.add(current)
            current = by_id[current].get("requires")
        done.update(trail)
    return result


def quote(text):
    # Fixed three-digit escapes avoid quotes, newlines, and digit ambiguity.
    return '"' + "".join(chr(byte) if 32 <= byte < 127 and byte not in (34, 92)
                         else f"\\{byte:03d}" for byte in text.encode("utf-8")) + '"'


def render(rows):
    lines = ["-- Generated by Flash Config. Edit the source catalog, then regenerate.", "return table.freeze({"]
    for item in rows:
        fields = [f"id = {quote(item['id'])}", f"name = {quote(item['name'])}", f"price = {item['price']}"]
        if "requires" in item:
            fields.append(f"requires = {quote(item['requires'])}")
        lines.append("    table.freeze({ " + ", ".join(fields) + " }),")
    return "\n".join(lines + ["})", ""])


def write_atomic(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=path.parent, delete=False) as stream:
            temp = Path(stream.name)
            stream.write(content)
        os.replace(temp, path)
    finally:
        if temp is not None:
            temp.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="validate without writing")
    mode.add_argument("--output", type=Path, help="write a .luau module")
    args = parser.parse_args(argv)
    try:
        if args.output and (args.output.suffix.lower() != ".luau" or args.input.resolve() == args.output.resolve()):
            raise CatalogError("output must be a separate .luau file")
        rows = load_catalog(args.input)
        if args.output:
            write_atomic(args.output, render(rows))
        print(f"Checked {len(rows)} items" + (f"; wrote {args.output}" if args.output else ""))
        return 0
    except (ValueError, OSError, UnicodeError, csv.Error, RecursionError) as error:
        print(f"flash-config: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
